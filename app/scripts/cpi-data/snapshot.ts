import type { CpiPoint } from "../../src/cpi/format.ts";

export type YearChange = readonly [year: number, pct: number];

/** The change of each calendar year (December to December), oldest first. Throws when a year is missing. */
export function decemberChanges(points: readonly CpiPoint[]): YearChange[] {
  const decembers = points.filter((point) => point.month === 12).sort((a, b) => a.year - b.year);
  if (decembers.length === 0) throw new Error("The answer has no December value.");
  for (let i = 1; i < decembers.length; i++) {
    if (decembers[i].year !== decembers[i - 1].year + 1) {
      throw new Error(`The answer has no December ${decembers[i - 1].year + 1} value.`);
    }
  }
  return decembers.map((point) => [point.year, point.yearOverYearPct]);
}

/** A reason not to publish the table, or null. A table that stops long before today has gone stale. */
export function findProblem(changes: readonly YearChange[], now: Date): string | null {
  if (changes.length < 60) return `Only ${changes.length} years found; expected about 70.`;
  const last = changes[changes.length - 1][0];
  if (last < now.getUTCFullYear() - 2) return `The newest year is ${last}, which is too old.`;
  return null;
}

/** The source of `src/cpi/snapshot.ts`. */
export function renderSnapshot(changes: readonly YearChange[], retrievedOn: string): string {
  const rows = changes.map(([year, pct]) => `  [${year}, ${pct}],`).join("\n");
  return `// Generated by \`npm run cpi-data\` from the Israeli Central Bureau of Statistics (api.cbs.gov.il).
// Do not edit by hand; run the command again to refresh it.

export const CPI_BUILT_IN_RETRIEVED_ON = "${retrievedOn}";

/** The change of the general consumer price index over each calendar year (December to December), in percent. */
export const CPI_BUILT_IN_DECEMBER_CHANGES: readonly (readonly [year: number, pct: number])[] = [
${rows}
];
`;
}
