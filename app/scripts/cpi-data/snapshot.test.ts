// @vitest-environment node
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { CPI_BUILT_IN_DECEMBER_CHANGES, CPI_BUILT_IN_RETRIEVED_ON } from "../../src/cpi/snapshot.ts";
import { decemberChanges, findProblem, renderSnapshot, type YearChange } from "./snapshot.ts";

const december = (year: number, yearOverYearPct: number) => ({ year, month: 12, yearOverYearPct });

describe("decemberChanges", () => {
  it("keeps the December of each year, oldest first", () => {
    const points = [
      december(2024, 3.2),
      { year: 2024, month: 6, yearOverYearPct: 2.9 },
      december(2023, 3),
      { year: 2025, month: 3, yearOverYearPct: 3.1 },
    ];
    expect(decemberChanges(points)).toEqual([
      [2023, 3],
      [2024, 3.2],
    ]);
  });

  it("throws without a December", () => {
    expect(() => decemberChanges([{ year: 2024, month: 6, yearOverYearPct: 2.9 }])).toThrow(/no December value/);
  });

  it("throws when a year is missing in between", () => {
    expect(() => decemberChanges([december(2020, 1), december(2022, 2)])).toThrow(/December 2021/);
  });
});

describe("findProblem", () => {
  const years = (from: number, to: number): YearChange[] =>
    Array.from({ length: to - from + 1 }, (_, index) => [from + index, 2]);
  const NOW = new Date("2026-10-31T12:00:00Z");

  it("accepts a long table that reaches last year", () => {
    expect(findProblem(years(1952, 2025), NOW)).toBeNull();
  });

  it("rejects a table that is too short", () => {
    expect(findProblem(years(2000, 2025), NOW)).toMatch(/Only 26 years/);
  });

  it("rejects a table that stopped long ago", () => {
    expect(findProblem(years(1952, 2020), NOW)).toMatch(/2020.*too old/);
  });
});

describe("renderSnapshot", () => {
  it("writes the date it was taken and one line per year", () => {
    const text = renderSnapshot(
      [
        [2024, 3.2],
        [2025, 2.6],
      ],
      "2026-10-31",
    );
    expect(text).toContain('CPI_BUILT_IN_RETRIEVED_ON = "2026-10-31"');
    expect(text).toContain("  [2024, 3.2],\n  [2025, 2.6],\n];");
    expect(text).toContain("Generated by `npm run cpi-data`");
  });

  it("is what the table in the app was generated from", () => {
    const file = readFileSync(new URL("../../src/cpi/snapshot.ts", import.meta.url), "utf8").replaceAll("\r\n", "\n");
    expect(file).toBe(renderSnapshot(CPI_BUILT_IN_DECEMBER_CHANGES, CPI_BUILT_IN_RETRIEVED_ON));
  });
});
